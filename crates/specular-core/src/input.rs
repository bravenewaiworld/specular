//! Buttons, as devices report them and as screens receive them.

use std::time::Duration;

/// The buttons Specular knows, by position on a typical handheld (A = right, B = bottom,
/// X = top, Y = left). A device may lack some; its profile says which it has. `Mute` is a
/// switch: pressed while the sound is switched off, released when it is switched on.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Button { Up, Down, Left, Right, A, B, X, Y, L1, R1, L2, R2, Select, Start, Menu, F1, F2, VolUp, VolDown, Power, Mute }

impl Button {
    /// Whether holding the button repeats it (moving through lists, jumping between letters,
    /// changing values, volume).
    pub fn repeats(self) -> bool {
        use Button::*;
        matches!(self, Up | Down | Left | Right | L1 | R1 | L2 | R2 | VolUp | VolDown)
    }

    /// Every button, with the name scripts and commands use for it.
    pub const NAMES: &[(Button, &str)] = &[
        (Button::Up, "up"), (Button::Down, "down"), (Button::Left, "left"), (Button::Right, "right"),
        (Button::A, "a"), (Button::B, "b"), (Button::X, "x"), (Button::Y, "y"),
        (Button::L1, "l1"), (Button::R1, "r1"), (Button::L2, "l2"), (Button::R2, "r2"),
        (Button::Select, "select"), (Button::Start, "start"), (Button::Menu, "menu"), (Button::F1, "f1"), (Button::F2, "f2"),
        (Button::VolUp, "volup"), (Button::VolDown, "voldown"), (Button::Power, "power"), (Button::Mute, "mute"),
    ];

    /// The button with this name (`NAMES`), in any case.
    pub fn named(name: &str) -> Option<Button> {
        Self::NAMES.iter().find(|(_, n)| n.eq_ignore_ascii_case(name)).map(|&(b, _)| b)
    }
}

/// A press or release, as a device reports it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ButtonEvent {
    pub button: Button,
    /// True for a press, false for a release.
    pub pressed: bool,
    /// When it happened, on the system's monotonic clock.
    pub time: Duration,
}

/// What screens act on: a press, either real or generated by holding the button.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Press {
    pub button: Button,
    /// Generated by holding the button. Lists wrap around at their ends only on a real press.
    pub repeat: bool,
}
