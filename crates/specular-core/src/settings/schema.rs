//! JSON Schemas documenting the settings files, generated from the declarations: every setting
//! a file may hold, with what it does, the values it takes and its default. Editors use them to
//! explain and check a file (each file points to its schema with `$schema`); Specular itself
//! never reads them.

use std::path::{Path, PathBuf};

use serde_json::{Map, Value, json};

use super::{choices, core_options, Layer, Scope, SettingDecl, SettingKind};
use crate::library::SystemDecl;

/// The schema of `layer`'s file, relative to the config folder. A system's games share one: their
/// settings depend only on the system.
pub fn file(layer: &Layer) -> PathBuf {
    match layer {
        Layer::Global => "specular.schema.json".into(),
        Layer::Core(core) => Path::new("cores").join(format!("{core}.schema.json")),
        Layer::System(system) => Path::new("systems").join(format!("{system}.schema.json")),
        Layer::Game { system, .. } => Path::new("games").join(format!("{system}.schema.json")),
    }
}

/// Every schema file, by its path relative to the config folder: the global one; then two for
/// each of `systems` (the ones playable, with a core), one for the system's file and one shared
/// by its games' files; then one for each of their cores' files.
pub fn all(decls: &[SettingDecl], systems: &[SystemDecl]) -> Vec<(PathBuf, Value)> {
    let global = schema(decls, &Layer::Global, &[], "Specular settings",
        "Specular's settings. This file holds only the settings you changed: any left out has the default shown here.");
    let per_system = systems.iter().flat_map(|s| {
        let cores: Vec<&str> = s.cores.iter().map(|c| c.id()).collect();
        let files = cores.iter().map(|c| format!("cores/{c}.json")).collect::<Vec<_>>().join(" or ");
        let also = if cores.is_empty() { String::new() } else { format!(", and {files} for the emulator's options") };
        let (id, ext) = (s.id, s.extensions.first().copied().unwrap_or("ext"));
        let (system, game) = (Layer::System(id.into()), Layer::Game { system: id.into(), game: String::new() });
        [
            (file(&system), schema(decls, &system, &cores, &format!("{} settings", s.name),
                &format!("Settings for all {} games, overriding specular.json{also}. This file is systems/{id}.json, and holds only the settings you changed.", s.name))),
            (file(&game), schema(decls, &game, &cores, &format!("{} game settings", s.name),
                &format!("Settings for one {} game, overriding systems/{id}.json and specular.json{also}. Make one file per game, named after its path under roms/ without the extension: roms/{id}/RPG/Some Game.{ext} → games/{id}/RPG/Some Game.json. A file for a game not in the library is ignored. This file holds only the settings you changed.", s.name))),
        ]
    });
    let per_core = crate::library::cores(systems).into_iter().map(|c| {
        let layer = Layer::Core(c.id().into());
        // A core the user added has no options listed until it has played a game (`user_cores`).
        let unlearned = if c.user.is_some() && core_options::list(c).options.is_empty() { " Its options appear here once it has played a game." } else { "" };
        (file(&layer), schema(decls, &layer, &[c.id()], &format!("{} options", c.name),
            &format!("The options of {}, the emulator, for every game it plays; each system's and each game's settings can override them. This file holds only the options you changed.{unlearned}", c.name)))
    });
    std::iter::once((file(&Layer::Global), global)).chain(per_system).chain(per_core).collect()
}

/// The schema of `layer`'s file: the settings that may be set there, Specular's own and the
/// options of `cores` (the system's). Keys it doesn't list are allowed, as Specular keeps them (a
/// plugin's settings, or a newer version's). A declared setting that can't be set in this file is
/// listed as never valid (`"not": {}`), saying where it can be, so editors flag it. Options of
/// cores not in `cores` are neither listed nor marked invalid: Specular takes them in any system's
/// or game's file (`settable_at`), and a key two cores share is declared under the first core only
/// (`declarations`), so it may belong to one of `cores` too.
pub fn schema(decls: &[SettingDecl], layer: &Layer, cores: &[&str], title: &str, description: &str) -> Value {
    let properties: Map<String, Value> = decls.iter().filter_map(|d| {
        let p = if !d.settable_at(layer) { json!({ "not": {}, "description": format!("Can only be set in {}, not in this file.", places(d)) }) }
            else if d.core.is_none_or(|c| cores.contains(&c)) { property(decls, d) }
            else { return None };
        Some((d.key.to_string(), p))
    }).collect();
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": "Generated by Specular, which never reads it, and read-only: edits to this file have no effect, and are lost when Specular rewrites it, which it may do at any time.",
        "title": title,
        "description": description,
        "type": "object",
        "properties": properties,
    })
}

/// One setting's entry. Its title has its section too, as labels repeat across sections (Display:
/// Brightness, Lights: Brightness).
fn property(decls: &[SettingDecl], d: &SettingDecl) -> Value {
    let places = places(d);
    let only = if places.contains(" or ") { "" } else { " only" };
    let set = format!("Can be set{only} in {places}.");
    let description = if d.help.is_empty() { set } else { format!("{} {set}", d.help) };
    let mut p = json!({ "title": format!("{}: {}", d.section, d.label), "description": description });
    match d.kind {
        SettingKind::Bool => p["type"] = "boolean".into(),
        SettingKind::Choice(_) | SettingKind::Colour { .. } => {
            // `enum`, not a `oneOf` of `const`s with titles: editors check and offer both, but
            // for a wrong value `enum` gets an error listing the valid ones. The labels go in
            // `enumDescriptions`, VS Code's, which it shows beside each value it offers; other
            // editors ignore it, as draft 2020-12 allows.
            let (values, labels): (Vec<_>, Vec<_>) = choices(decls, d).into_iter().unzip();
            (p["type"], p["enum"], p["enumDescriptions"]) = ("string".into(), values.into(), labels.into());
        }
        SettingKind::Int { min, max, step, .. } => {
            (p["type"], p["minimum"], p["maximum"]) = ("integer".into(), min.into(), max.into());
            // multipleOf counts from 0 and our steps from `min`: they agree only if `min` is a
            // multiple of `step`, and otherwise the step is left out.
            if step > 1 && min % step == 0 { p["multipleOf"] = step.into(); }
        }
    }
    p["default"] = d.default.clone();
    p
}

/// The files `d` may be set in (`settable_at`), least specific first: "specular.json,
/// systems/<id>.json or a game's file in games/".
fn places(d: &SettingDecl) -> String {
    let base = d.core.map_or("specular.json".into(), |c| format!("cores/{c}.json"));
    let files: Vec<String> = match d.system {
        // A system's own setting is set in its files alone.
        Some(s) => [Some(format!("systems/{s}.json")), (d.deepest == Scope::Game).then(|| format!("a {s} game's file in games/"))].into_iter().flatten().collect(),
        None => [Some(base), (d.deepest >= Scope::System).then(|| "systems/<id>.json".into()), (d.deepest == Scope::Game).then(|| "a game's file in games/".into())]
            .into_iter().flatten().collect(),
    };
    match files.split_last() {
        Some((last, rest)) if !rest.is_empty() => format!("{} or {last}", rest.join(", ")),
        _ => files.concat(),
    }
}
